#include "I18n.hpp"
#include <QLocale>

I18n& I18n::instance() {
    static I18n inst;
    return inst;
}

I18n::I18n() {
    setLanguageFromSystem();
}

void I18n::setLanguageFromSystem() {
    const QString loc = QLocale::system().name();
    if (loc.startsWith(QLatin1String("ru")))
        setLanguage(Russian);
    else
        setLanguage(English);
}

void I18n::setLanguage(Lang lang) {
    lang_ = lang;
    dict_.clear();
    if (lang == Russian)
        loadRussian();
    else
        loadEnglish();
}

QString I18n::tr(const char* key) const {
    const QString k = QString::fromUtf8(key);
    auto it = dict_.constFind(k);
    if (it != dict_.constEnd())
        return it.value();
    return k;
}

QString I18n::tr(const char* key, const QString& fallback) const {
    const QString k = QString::fromUtf8(key);
    auto it = dict_.constFind(k);
    if (it != dict_.constEnd())
        return it.value();
    return fallback;
}

